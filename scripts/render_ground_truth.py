#!/usr/bin/env python3
"""Render ground-truth documents as GitHub Flavored Markdown that a coding agent can cite.

The original document stays the source of truth. This script writes a derived
rendering for readers and agents:

  docs/ground-truth/<name>.md          the rendering, with a generated header and a section index
  docs/ground-truth/<name>.index.txt   one line per heading, "line:## heading", for sed-based reading
  docs/ground-truth/figures/<name>/    figures extracted from a .docx, or copied from a .md

Input can be a Word document (.docx), a Markdown file (.md) or UTF-8 text (.txt). Nothing needs to be
installed: Word files are read with the standard library (zipfile and xml.etree). If the
lxml package happens to be installed, the script uses it because it is faster.

Examples
  python3 scripts/render_ground_truth.py architecture.docx --version 0.2
  python3 scripts/render_ground_truth.py notes.md standards.md --out-dir docs/ground-truth
  python3 scripts/render_ground_truth.py architecture.docx --dry-run

With --dry-run nothing is written. The script reports what it would write.
Every input is read and rendered, and every output path is checked, before anything is written,
so a failure leaves the folder as it was. A source kept inside docs/ground-truth/, one whose
rendering would land on itself, and two inputs that would render to the same name are refused.
Keep sources in docs/source/.

Confidential projects (a plan with `project.handling` or a classification on its sources)
  A rendering of a source that is not approved for everyone who can read the repository goes to the
  private workspace, in <workspace>/renderings/, never into the project. Header and footer text of a
  Word file is recorded in the header comment as `markings:`, and a marking such as "Internal" on a
  source classified for repository readers stops the run until --accept-marking-mismatch. Hidden text,
  tracked insertions and tracked deletions stop the run until the owner decides with
  --resolve-review-items include|exclude; --show-review-items lists them for the owner. Links
  other than http and https are dropped, keeping the link text. HTML comments in Markdown are removed.
  A plan without these fields renders as it always did.
"""
