IMAGE_EXTENSIONS = {".png", ".jpg", ".jpeg", ".gif", ".svg", ".webp", ".bmp"}


class Figures:
    """The figures of one document, in memory until main writes them. Two figures with the same
    file name from different places get different names, so neither overwrites the other."""

    def __init__(self):
        self.files = []    # (name, bytes)
        self._by_key = {}
        self._names = set()

    def add(self, name, data, key=None):
        if key is not None and key in self._by_key:
            return self._by_key[key]
        stem, ext = os.path.splitext(name)
        final, n = name, 1
        while final.casefold() in self._names:
            n += 1
            final = f"{stem}-{n}{ext}"
        self._names.add(final.casefold())
        self.files.append((final, data))
        if key is not None:
            self._by_key[key] = final
        return final

    def __len__(self):
        return len(self.files)


def new_info():
    """What a rendering found that the owner may need to decide on. markings: header and footer
    text of a Word file. items: hidden or tracked content, as (paragraph number, kind, text).
    links_removed and comments_removed are counts."""
    return {"markings": [], "items": [], "links_removed": 0, "comments_removed": 0}


SCHEME = re.compile(r"^[A-Za-z][A-Za-z0-9+.\-]*:")


def clean_target(target):
    """A link target without the spaces and control characters a browser ignores before the scheme,
    so "java\nscript:" and " file:" are read the way a browser reads them."""
    return re.sub(r"[\x00-\x20\x7f]", "", str(target))


def link_is_web(target):
    """True for an http or https link, the only schemes the renderer keeps."""
    return clean_target(target).lower().startswith(("http://", "https://"))


def link_has_other_scheme(target):
    """True for a link with a scheme other than http or https, such as mailto: or file:."""
    t = clean_target(target)
    return bool(SCHEME.match(t)) and not link_is_web(t)


HTML_COMMENT = re.compile(r"(?P<code>(`+)(?:(?!\2)[^\n]|\n(?!\s*\n))+?\2)|(?P<comment><!--.*?(?:-->|\Z))", re.S)
MD_LINK = re.compile(r"(?<!\!)\[([^\]]*)\]\(\s*<?([^)\s>]*)>?(?:\s[^)]*)?\)")


def strip_html_comments(text):
    """Remove HTML comments from Markdown outside fenced code blocks and inline code. Return
    (text, number removed). A comment is where reviewers leave notes the readers should not see,
    and a comment that is never closed hides the rest of the document, so it is removed too."""
    removed = 0

    def repl(m):
        nonlocal removed
        if m.group("comment") is None:
            return m.group(0)
        removed += 1
        return ""

    out, chunk, fence = [], [], None

    def flush():
        if chunk:
            out.append(HTML_COMMENT.sub(repl, "\n".join(chunk)))
            chunk.clear()

    for line in text.split("\n"):
        m = re.match(r"^\s{0,3}(`{3,}|~{3,})", line)
        if m:
            tok = m.group(1)
            if fence is None:
                flush()
                fence = tok[0]
                out.append(line)
                continue
            if tok[0] == fence:
                fence = None
                out.append(line)
                continue
        if fence:
            out.append(line)
        else:
            chunk.append(line)
    flush()
    return "\n".join(out), removed


def drop_other_scheme_links(line):
    """Replace [text](target) by its text when target has a scheme other than http or https.
    Relative links and anchors stay. Inline code is left as written. Return (line, number dropped)."""
    dropped = 0

    def link(m):
        nonlocal dropped
        if link_has_other_scheme(m.group(2)):
            dropped += 1
            return m.group(1)
        return m.group(0)

    pieces = re.split(r"(`+[^`]*`+)", line)
    for i in range(0, len(pieces), 2):
        pieces[i] = MD_LINK.sub(link, pieces[i])
    return "".join(pieces), dropped


def render_markdown(src, fig_prefix):
    try:
        text = Path(src).read_text(encoding="utf-8-sig")
    except UnicodeDecodeError as e:
        raise DocxError(f"is not UTF-8 text (byte 0x{e.object[e.start]:02x} at offset {e.start}). Save it as UTF-8, then run this again")
    text = text.replace("\r\n", "\n").replace("\r", "\n").replace("\t", "    ")
    text = re.sub(r"^<!-- Generated from .*?-->\s*\n", "", text, flags=re.S)
    text, comments = strip_html_comments(text)
    info = new_info()
    info["comments_removed"] = comments
    lines = text.split("\n")
    notes = []
    figs = Figures()
    out = []
    fence = None
    for line in lines:
        m = re.match(r"^\s{0,3}(`{3,}|~{3,})", line)
        if m:
            tok = m.group(1)
            if fence is None:
                fence = tok[0]
            elif tok[0] == fence:
                fence = None
            out.append(line)
            continue
        if fence:
            out.append(line)
            continue

        def repl(mo):
            alt, target = mo.group(1), mo.group(2).strip()
            if re.match(r"^[a-z]+://", target) or target.startswith("#") or target.startswith("data:"):
                return mo.group(0)
            base = Path(src).parent.resolve()
            local = (base / target.split(" ")[0]).resolve()
            # copy only images that sit in the document's own folder or below it, so a link such as
            # ../../.env or /home/me/.ssh/id_ed25519 can never put a private file into the repository
            if base not in local.parents or local.suffix.lower() not in IMAGE_EXTENSIONS:
                notes.append(f"not copied (outside the document folder or not an image): {target}")
                return mo.group(0)
            try:
                found = local.is_file()
            except (OSError, ValueError):
                found = False
            if not found:
                notes.append(f"image not found, or not a regular file: {target}")
                return mo.group(0)
            try:
                data = local.read_bytes()
            except OSError as e:
                notes.append(f"image not readable ({e.strerror or e}): {target}")
                return mo.group(0)
            name = figs.add(local.name, data, key=str(local))
            return f"![{alt}]({fig_prefix}/{name})"

        line = re.sub(r"!\[([^\]]*)\]\(([^)]+)\)", repl, line)
        line, dropped = drop_other_scheme_links(line)
        info["links_removed"] += dropped
        out.append(line)
    h1 = [h for h in collect_headings(out) if h[1] == 1]
    if not any(line.strip() for line in out):
        notes.append("the document is empty.")
    elif len(h1) == 0:
        notes.append("no top-level heading (#). A title was added from the file name.")
    elif len(h1) > 1:
        notes.append(f"{len(h1)} top-level headings. Use one # title and ## for sections so anchors stay readable.")
    return out, figs, notes, info


def render_text(src):
    """Put plain UTF-8 text in one numbered section without interpreting it as Markdown."""
    try:
        text = Path(src).read_text(encoding="utf-8-sig")
    except UnicodeDecodeError as e:
        raise DocxError(f"is not UTF-8 text (byte 0x{e.object[e.start]:02x} at offset {e.start}). Save it as UTF-8, then run this again")
    text = text.replace("\r\n", "\n").replace("\r", "\n").replace("\t", "    ")
    notes = [] if text.strip() else ["the document is empty."]
    body = [f"# {Path(src).stem}", "", "## 1 Source text", "", "````text", text.rstrip(), "````"]
    return body, Figures(), notes, new_info()


