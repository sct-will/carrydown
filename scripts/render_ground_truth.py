def num(value, default=None, signed=False):
    """A whole number from a Word attribute, or default. ASCII digits only and at most nine, so a
    damaged or crafted document cannot make int() fail or build a huge number."""
    s = str(value).strip() if value is not None else ""
    return int(s) if re.fullmatch(r"-?[0-9]{1,9}" if signed else r"[0-9]{1,9}", s) else default


def q(tag, ns=W):
    return "{%s}%s" % (ns, tag)


class DocxError(Exception):
    pass


NUMBERED_HEADING = re.compile(r"^\d+(\.\d+)*\.?\s")


def _roman(n):
    vals = ((1000, "m"), (900, "cm"), (500, "d"), (400, "cd"), (100, "c"), (90, "xc"),
            (50, "l"), (40, "xl"), (10, "x"), (9, "ix"), (5, "v"), (4, "iv"), (1, "i"))
    out = []
    for v, s in vals:
        while n >= v:
            out.append(s)
            n -= v
    return "".join(out) or "0"


def _letters(n):
    out = ""
    while n > 0:
        n, r = divmod(n - 1, 26)
        out = chr(97 + r) + out
    return out or "0"


def format_number(n, fmt):
    """Format a list counter the way Word does for the common number formats."""
    if fmt in ("lowerLetter", "upperLetter"):
        s = _letters(n)
        return s.upper() if fmt == "upperLetter" else s
    if fmt in ("lowerRoman", "upperRoman"):
        s = _roman(n)
        return s.upper() if fmt == "upperRoman" else s
    if fmt == "decimalZero":
        return f"{n:02d}"
    if fmt in ("bullet", "none"):
        return ""
    return str(n)


class Numbering:
    """Word list numbering: abstract definitions from numbering.xml, counters in document order.

    Counters are kept per abstract definition, so two list instances (w:num) that point at the
    same definition continue each other, as Word does. A w:startOverride restarts a level the
    first time its instance is used. A level restarts when a higher level is used, unless its
    w:lvlRestart says otherwise."""

    def __init__(self, root, q, styles):
        self.levels = {}       # abstractNumId -> {ilvl: level dict}
        self.nums = {}         # numId -> (abstractNumId, {ilvl: start override})
        self.counters = {}     # abstractNumId -> {ilvl: current value or None}
        self.pending = {}      # (abstractNumId, ilvl) -> start value of a restarted level
        self.used = set()
        if root is None:
            return
        links = {}
        for a in root.findall(q("abstractNum")):
            aid = a.get(q("abstractNumId"))
            lv = {}
            for l in a.findall(q("lvl")):
                ilvl = num(l.get(q("ilvl")), 0)

                def val(tag, default=None):
                    e = l.find(q(tag))
                    return e.get(q("val")) if e is not None else default
                start = val("start", "1")
                restart = val("lvlRestart")
                lv[ilvl] = {
                    "fmt": val("numFmt", "decimal"),
                    "text": val("lvlText"),
                    "start": num(start, 1, signed=True),
                    "restart": num(restart),
                    "pstyle": val("pStyle"),
                    "legal": l.find(q("isLgl")) is not None,
                }
            self.levels[aid] = lv
            link = a.find(q("numStyleLink"))
            if link is not None:
                links[aid] = link.get(q("val"))
        for n in root.findall(q("num")):
            ref = n.find(q("abstractNumId"))
            ov = {}
            for o in n.findall(q("lvlOverride")):
                so = o.find(q("startOverride"))
                if so is not None and num(so.get(q("val"))) is not None:
                    ov[num(o.get(q("ilvl")), 0)] = num(so.get(q("val")))
            self.nums[n.get(q("numId"))] = (ref.get(q("val")) if ref is not None else None, ov)
        # an abstract definition that only links to a numbering style borrows that style's list
        for aid, sid in links.items():
            if self.levels.get(aid):
                continue
            nid = (styles.get(sid) or {}).get("numId")
            target = self.nums.get(nid, (None, {}))[0]
            if target and target != aid:
                self.levels[aid] = self.levels.get(target, {})

    def abstract_of(self, num_id):
        return self.nums.get(num_id, (None, {}))[0]

    def level(self, num_id, ilvl):
        return self.levels.get(self.abstract_of(num_id), {}).get(ilvl)

    def level_for_style(self, num_id, style_id):
        for ilvl, lv in self.levels.get(self.abstract_of(num_id), {}).items():
            if lv["pstyle"] == style_id:
                return ilvl
        return None

    def advance(self, num_id, ilvl):
        """Count one paragraph of list num_id at level ilvl. Return (label, format of the level)."""
        aid = self.abstract_of(num_id)
        levels = self.levels.get(aid)
        if not levels or ilvl not in levels:
            return "", "bullet"
        c = self.counters.setdefault(aid, {})
        if num_id not in self.used:
            self.used.add(num_id)
            for l, s in self.nums[num_id][1].items():
                c[l] = None
                self.pending[(aid, l)] = s
        lv = levels[ilvl]
        if c.get(ilvl) is None:
            c[ilvl] = self.pending.pop((aid, ilvl), lv["start"])
        else:
            c[ilvl] += 1
        for d, dl in levels.items():
            if d > ilvl:
                restart = dl["restart"] if dl["restart"] is not None else d
                if restart != 0 and ilvl + 1 <= restart:
                    c[d] = None
        if lv["fmt"] in ("bullet", "none"):
            return "", lv["fmt"]
        text = lv["text"] if lv["text"] is not None else f"%{ilvl + 1}."

        def sub(m):
            k = int(m.group(1)) - 1
            kl = levels.get(k)
            if kl is None:
                return ""
            v = c.get(k)
            if v is None:
                v = kl["start"]
            return format_number(v, "decimal" if lv["legal"] else kl["fmt"])
        return re.sub(r"%([1-9])", sub, text).strip(), lv["fmt"]


XML_ENCODINGS = {"utf-8", "utf8", "utf-16", "utf16", "us-ascii", "ascii"}


def refuse_dtd(name, data):
    """Refuse an XML part that declares a DOCTYPE or an ENTITY, in any encoding and at any position.
    Word never writes either one, and a DOCTYPE is how entity expansion and external entity attacks
    reach an XML parser. A part in an encoding other than UTF-8 or UTF-16 is refused too, because
    the check could not read it."""
    head = data.lstrip(b" \t\r\n")
    if data[:4] in (b"\x00\x00\xfe\xff", b"\xff\xfe\x00\x00") or head[:4] in (b"<\x00\x00\x00", b"\x00\x00\x00<"):
        raise DocxError(f"{name} is UTF-32 XML, and Word writes only UTF-8 or UTF-16. The document was not parsed")
    if data[:3] == b"\xef\xbb\xbf":
        enc = "utf-8"
    elif data[:2] in (b"\xff\xfe", b"\xfe\xff") or head[:2] in (b"<\x00", b"\x00<"):
        enc = "utf-16"
    elif head[:1] != b"<":
        raise DocxError(f"{name} is not UTF-8 or UTF-16 XML, which is all Word writes. The document was not parsed")
    else:
        enc = "utf-8"
        m = re.match(rb"<\?xml[^>]*?encoding\s*=\s*[\"']([A-Za-z0-9._-]+)[\"']", head)
        if m and m.group(1).decode("ascii").lower() not in XML_ENCODINGS:
            raise DocxError(f"{name} declares the encoding {m.group(1).decode('ascii')}, and Word writes only UTF-8 or UTF-16. The document was not parsed")
    texts = {data.decode(e, "replace") for e in ("utf-8", "utf-16-le", "utf-16-be")}
    texts.add(data.decode(enc, "replace"))
    for text in texts:
        found = re.search(r"<!\s*(DOCTYPE|ENTITY)", text, re.I)
        if found:
            kind = found.group(1).upper()
            raise DocxError(f"{name} contains {'an' if kind == 'ENTITY' else 'a'} {kind} declaration, which Word never writes. The document was not parsed")


def render_docx(src, fig_prefix):
    try:
        from lxml import etree   # optional and faster
        parse_errors = (etree.XMLSyntaxError, ValueError)
    except ImportError:
        import xml.etree.ElementTree as etree
        parse_errors = (etree.ParseError, ValueError)
    try:
        z = zipfile.ZipFile(src)
    except zipfile.BadZipFile:
        raise DocxError("not a Word document (the file is not a zip archive)")
    members = set(z.namelist())

    def read_member(name):
        try:
            return z.read(name)
        except (zipfile.BadZipFile, zlib.error, EOFError, RuntimeError, NotImplementedError, KeyError, ValueError) as e:
            raise DocxError(f"{name} cannot be read from the Word document ({e}). Save the document again in Word")

    def read_part(name):
        """Parse one XML part, after refuse_dtd has checked it."""
        data = read_member(name)
        refuse_dtd(name, data)
        try:
            return etree.fromstring(data)
        except parse_errors as e:
            raise DocxError(f"{name} is not well-formed XML ({str(e)[:120]}). Save the document again in Word")

    if "word/document.xml" not in members:
        raise DocxError("word/document.xml is missing, so this is not a Word document")
    doc = read_part("word/document.xml")
    body = doc.find(q("body"))
    if body is None:
        raise DocxError("word/document.xml has no body, so this is not a Word document")
    rels = {}
    if "word/_rels/document.xml.rels" in members:
        rels_xml = read_part("word/_rels/document.xml.rels")
        rels = {r.get("Id"): r.get("Target") for r in rels_xml}

    # styles: id -> name, parent, numbering and outline level
    styles = {}
    if "word/styles.xml" in members:
        for s in read_part("word/styles.xml").findall(q("style")):
            sid = s.get(q("styleId"))
            if not sid:
                continue
            info = {"name": None, "based": None, "numId": None, "ilvl": None, "outline": None}
            e = s.find(q("name"))
            info["name"] = e.get(q("val")) if e is not None else None
            e = s.find(q("basedOn"))
            info["based"] = e.get(q("val")) if e is not None else None
            ppr = s.find(q("pPr"))
            if ppr is not None:
                numpr = ppr.find(q("numPr"))
                if numpr is not None:
                    e = numpr.find(q("numId"))
                    info["numId"] = e.get(q("val")) if e is not None else None
                    e = numpr.find(q("ilvl"))
                    info["ilvl"] = num(e.get(q("val"))) if e is not None else None
                e = ppr.find(q("outlineLvl"))
                if e is not None and num(e.get(q("val"))) is not None:
                    info["outline"] = num(e.get(q("val")))
            styles[sid] = info

    def style_attr(sid, key):
        seen = set()
        while sid and sid in styles and sid not in seen:
            seen.add(sid)
            v = styles[sid][key]
            if v is not None:
                return v
            sid = styles[sid]["based"]
        return None

    numbering = Numbering(read_part("word/numbering.xml") if "word/numbering.xml" in members else None, q, styles)

    def style_of(p):
        ps = p.find(q("pPr") + "/" + q("pStyle"))
        return ps.get(q("val")) if ps is not None else "Normal"

    def style_name(st):
        return (styles.get(st) or {}).get("name") or st or ""

    def is_title(st):
        return st == "Title" or style_name(st).lower() == "title"

    def is_subtitle(st):
        return st == "Subtitle" or style_name(st).lower() == "subtitle"

    def heading_level(p, st=None):
        """Heading level 1 to 9, or None. Word stores the built-in style names in English
        ("heading 1") whatever the language of the user interface, so the name is checked
        before the style id. A paragraph or style outline level also marks a heading."""
        st = st or style_of(p)
        ol = p.find(q("pPr") + "/" + q("outlineLvl"))
        if ol is not None and num(ol.get(q("val"))) is not None:
            v = num(ol.get(q("val")))
            return v + 1 if v <= 8 else None
        for cand in (style_name(st), st):
            m = re.fullmatch(r"(?i)heading\s*([1-9])", cand or "")
            if m:
                return int(m.group(1))
        v = style_attr(st, "outline")
        if v is not None and v <= 8:
            return v + 1
        return None

    def para_numbering(p, st):
        """(numId, ilvl) of a paragraph, from the paragraph or its style, or None."""
        numpr = p.find(q("pPr") + "/" + q("numPr"))
        nid = ilvl = None
        if numpr is not None:
            e = numpr.find(q("numId"))
            nid = e.get(q("val")) if e is not None else None
            e = numpr.find(q("ilvl"))
            ilvl = num(e.get(q("val"))) if e is not None else None
        if nid is None:
            nid = style_attr(st, "numId")
            if ilvl is None:
                ilvl = style_attr(st, "ilvl")
        if nid in (None, "0"):
            return None
        if ilvl is None:
            ilvl = numbering.level_for_style(nid, st)
        return nid, (ilvl or 0)

    SKIP_TAGS = (q("del"), q("moveFrom"))
    # inline elements whose runs are part of the paragraph text
    CONTAINERS = (q("ins"), q("moveTo"), q("smartTag"), q("fldSimple"), q("customXml"), q("sdt"), q("sdtContent"))

    def ptext(p):
        parts = []

        def walk(node):
            for child in node:
                if child.tag in SKIP_TAGS:
                    continue
                if child.tag == q("t") and child.text:
                    parts.append(child.text)
                elif child.tag == q("tab"):
                    parts.append("\t")
                elif child.tag == q("br"):
                    parts.append("\n")
                walk(child)
        walk(p)
        return "".join(parts)

    def blocks(container):
        """Body-level elements in order. Content controls and custom XML are opened; Word's own
        table of contents control is skipped (the generated section index replaces it)."""
        for el in container:
            if el.tag == q("sdt"):
                gal = el.find(q("sdtPr") + "/" + q("docPartObj") + "/" + q("docPartGallery"))
                if gal is not None and "contents" in (gal.get(q("val")) or "").lower():
                    continue
                content = el.find(q("sdtContent"))
                if content is not None:
                    yield from blocks(content)
            elif el.tag == q("customXml"):
                yield from blocks(el)
            else:
                yield el

    children = list(blocks(body))

    # numbers in document order. Every numbered paragraph counts, in tables too, as in Word.
    labels = {}
    list_fmt = {}
    for p in body.iter(q("p")):
        st = style_of(p)
        np_ = para_numbering(p, st)
        if np_:
            label, fmt = numbering.advance(*np_)
            labels[p] = label
            list_fmt[p] = (np_[0], np_[1], fmt)

    def heading_text(p):
        t = norm(ptext(p))
        label = labels.get(p, "")
        if label and t and not t.startswith(label + " "):
            t = f"{label} {t}"
        return t

    def rfont_mono(rf):
        return rf is not None and any(any(m in (rf.get(q(k)) or "") for m in MONO_FONTS) for k in ("ascii", "hAnsi", "cs"))

    def run_is_mono(r):
        rpr = r.find(q("rPr"))
        return rpr is not None and rfont_mono(rpr.find(q("rFonts")))

    def run_flag(r, tag):
        rpr = r.find(q("rPr"))
        if rpr is None:
            return False
        e = rpr.find(q(tag))
        return e is not None and e.get(q("val")) not in ("0", "false")

    def run_text(r):
        parts = []
        for node in r:
            if node.tag == q("t") and node.text:
                parts.append(node.text)
            elif node.tag == q("tab"):
                parts.append("  ")
            elif node.tag == q("br"):
                parts.append("\n")
        return "".join(parts)

    def para_is_mono(p):
        runs = [r for r in p.iter(q("r")) if run_text(r).strip()]
        if runs and all(run_is_mono(r) for r in runs):
            return True
        ppr = p.find(q("pPr"))
        if ppr is not None:
            mark = ppr.find(q("rPr"))
            if mark is not None and rfont_mono(mark.find(q("rFonts"))):
                return bool(runs) and all(r.find(q("rPr")) is None or r.find(q("rPr") + "/" + q("rFonts")) is None for r in runs)
        return False

    def para_is_shaded(p):
        shd = p.find(q("pPr") + "/" + q("shd"))
        return shd is not None and (shd.get(q("fill")) or "auto").lower() not in ("auto", "ffffff")

    def norm(t):
        return " ".join(t.split())

    # heading slugs in document order, the way GitHub derives anchors
    def is_heading(p):
        st = style_of(p)
        return is_title(st) or heading_level(p, st) is not None

    heading_texts = []
    for p in children:
        if p.tag == q("p") and is_heading(p):
            t = heading_text(p)
            if t:
                heading_texts.append(t)
    counts = {}
    slug_list = []
    for t in heading_texts:
        b = slugify(re.sub(r"[`*_]", "", t))
        n = counts.get(b, 0)
        counts[b] = n + 1
        slug_list.append(b if n == 0 else f"{b}-{n}")
    text_to_slug = {}
    for t, sl in zip(heading_texts, slug_list):
        text_to_slug.setdefault(t, sl)

    bm_to_slug = {}
    pending = []
    for p in children:
        if p.tag != q("p"):
            continue
        marks = [b.get(q("name")) for b in p.iter(q("bookmarkStart"))]
        t = heading_text(p) if is_heading(p) else ""
        if t:
            sl = text_to_slug[t]
            for n in marks + pending:
                bm_to_slug[n] = sl
            pending = []
        else:
            pending.extend(marks)

    def inline(p, in_table=False):
        out = []

        def emit_runs(runs):
            buf = []
            state = {"kind": None, "text": ""}

            def flush():
                t, kind = state["text"], state["kind"]
                if not t:
                    return
                stripped = t.strip()
                lead = t[: len(t) - len(t.lstrip())]
                trail = t[len(t.rstrip()):]
                if kind == "m":
                    buf.append(lead + "`" + stripped + "`" + trail if stripped else t)
                elif kind in ("b", "i"):
                    mark = "**" if kind == "b" else "*"
                    buf.append(lead + mark + esc_prose(stripped) + mark + trail if stripped else t)
                else:
                    buf.append(esc_prose(t))
                state["text"] = ""

            for r in runs:
                t = run_text(r)
                if not t:
                    continue
                kind = "m" if run_is_mono(r) else "b" if run_flag(r, "b") else "i" if run_flag(r, "i") else "n"
                if kind != state["kind"]:
                    flush()
                    state["kind"] = kind
                state["text"] += t
            flush()
            return "".join(buf)

        def runs_in(node):
            for child in node:
                if child.tag in SKIP_TAGS:
                    continue
                if child.tag == q("r"):
                    yield child
                elif child.tag in CONTAINERS:
                    yield from runs_in(child)

        def walk(node):
            for child in node:
                if child.tag == q("r"):
                    out.append(emit_runs([child]))
                elif child.tag == q("hyperlink"):
                    text = emit_runs(list(runs_in(child)))
                    anchor = child.get(q("anchor"))
                    rid = child.get(q("id", R))
                    if anchor and anchor in bm_to_slug:
                        out.append(f"[{text}](#{bm_to_slug[anchor]})")
                    elif rid and rid in rels:
                        out.append(f"[{text}]({rels[rid]})")
                    else:
                        out.append(text)
                elif child.tag in CONTAINERS:
                    walk(child)

        walk(p)
        text = "".join(out)
        text = text.replace("****", "").replace("` `", " ")
        text = re.sub(r"`([^`]*)``([^`]*)`", r"`\1\2`", text)
        if in_table:
            text = esc_cell(text).replace("\n", "<br>")
        return text

    def list_prefix(p):
        """("1." or "-", indent) for a list paragraph, or (None, 0). The indent nests a level under
        the text of its parent item, as GitHub Flavored Markdown needs."""
        info = list_fmt.get(p)
        if info is None:
            return None, 0
        nid, ilvl, fmt = info

        def mark(f):
            return "-" if f in ("bullet", "none") else "1."
        indent = 0
        for k in range(ilvl):
            lv = numbering.level(nid, k)
            indent += len(mark(lv["fmt"] if lv else "bullet")) + 1
        return mark(fmt), indent

    def code_lang(lines):
        first = next((l.strip() for l in lines if l.strip()), "")
        if first.startswith(("{", "[", '"')):
            return "json"
        if first.startswith(("import ", "const ", "export ", "await ", "(async", "function ")):
            return "js"
        if first.startswith("<"):
            return "html"
        if re.match(r"(?i)^(select|insert|update|create table|alter table)\b", first):
            return "sql"
        if first.startswith(("$ ", "npm ", "git ", "curl ", "python")):
            return "bash"
        return "text"

    def table_md(tbl):
        rows = []
        for tr in tbl.findall(q("tr")):
            cells = []
            for tc in tr.findall(q("tc")):
                paras = [inline(cp, in_table=True) for cp in tc.findall(q("p"))]
                paras = [x for x in paras if x.strip()]
                cells.append("<br>".join(paras) if paras else " ")
            rows.append(cells)
        if not rows:
            return []
        width = max(len(r) for r in rows)
        rows = [r + [" "] * (width - len(r)) for r in rows]
        lines = ["| " + " | ".join(rows[0]) + " |", "| " + " | ".join(["---"] * width) + " |"]
        for r in rows[1:]:
            lines.append("| " + " | ".join(r) + " |")
        return lines

    def drawing_target(p):
        for blip in p.iter(q("blip", A)):
            rid = blip.get(q("embed", R))
            if rid in rels:
                return rels[rid]
        return None

    md = []
    code_buf = []
    fig_counter = 0
    figs = Figures()
    pending_caption = None
    notes = []

    # footnotes, endnotes and comments are not rendered. Say so, one note each.
    def part_texts(name, tag):
        if name not in members:
            return {}
        return {e.get(q("id")): norm(ptext(e)) for e in read_part(name).findall(q(tag))}
    foot = part_texts("word/footnotes.xml", "footnote")
    endn = part_texts("word/endnotes.xml", "endnote")
    n_comments = 0
    for el in children:
        for ref in el.iter(q("footnoteReference")):
            fid = ref.get(q("id"))
            snippet = (foot.get(fid) or "")[:60]
            notes.append(f"footnote {fid} was not rendered" + (f": {snippet}" if snippet else ""))
        for ref in el.iter(q("endnoteReference")):
            fid = ref.get(q("id"))
            snippet = (endn.get(fid) or "")[:60]
            notes.append(f"endnote {fid} was not rendered" + (f": {snippet}" if snippet else ""))
        n_comments += sum(1 for _ in el.iter(q("commentReference")))
        if any(True for _ in el.iter(q("txbxContent"))):
            notes.append("text inside a text box was rendered as part of the paragraph that holds it: " + norm(ptext(el))[:60])
    if n_comments:
        notes.append(f"{n_comments} comment(s) were not rendered")

    def flush_code():
        nonlocal code_buf
        if code_buf:
            md.append("```" + code_lang(code_buf))
            md.extend(l.rstrip() for l in code_buf)
            md.append("```")
            md.append("")
            code_buf = []

    for i, el in enumerate(children):
        if el.tag == q("tbl"):
            flush_code()
            md.extend(table_md(el))
            md.append("")
            continue
        if el.tag != q("p"):
            continue
        p = el
        st = style_of(p)
        text = ptext(p)
        stripped = text.strip()

        target = drawing_target(p)
        if target:
            flush_code()
            fig_counter += 1
            caption = ""
            for nxt in children[i + 1:i + 3]:
                if nxt.tag == q("p"):
                    t = ptext(nxt).strip()
                    if t:
                        if re.match(r"^(Figure|Fig\.?) \d+[.:]", t):
                            caption = t
                        break
            m = re.match(r"^(?:Figure|Fig\.?) (\d+)[.:]", caption)
            ext = Path(target).suffix or ".png"
            name = f"figure-{m.group(1)}{ext}" if m else f"figure-{fig_counter}{ext}"
            member = "word/" + target if not target.startswith("/") else target.lstrip("/")
            if member not in members:
                member = "word/media/" + Path(target).name
            alt = re.sub(r"^(?:Figure|Fig\.?) \d+[.:]\s*", "", caption).rstrip(".") if caption else f"Figure {fig_counter}"
            if member not in members:
                notes.append(f"figure {fig_counter} was not rendered: the document has no image part {target}")
                md.append(f"*{esc_prose(alt)} (image missing from the document)*")
                md.append("")
                pending_caption = caption
                continue
            name = figs.add(name, read_member(member), key=member)
            md.append(f"![{esc_prose(alt)}]({fig_prefix}/{name})")
            md.append("")
            pending_caption = caption
            continue

        if not stripped:
            flush_code()
            continue

        # skip Word's own table of contents. The generated section index replaces it.
        if st.upper().startswith("TOC") or any((l.get(q("anchor")) or "").lower().startswith(("_toc", "toc_")) for l in p.findall(q("hyperlink"))):
            flush_code()
            continue

        if is_title(st):
            flush_code()
            md.append("# " + esc_prose(norm(stripped)))
            md.append("")
            continue
        if is_subtitle(st):
            md.append("*" + esc_prose(stripped) + "*")
            md.append("")
            continue
        lvl = heading_level(p, st)
        if lvl:
            flush_code()
            md.append("#" * min(lvl + 1, 6) + " " + esc_prose(heading_text(p)))
            md.append("")
            continue

        if pending_caption and stripped == pending_caption:
            md.append("*" + esc_prose(stripped) + "*")
            md.append("")
            pending_caption = None
            continue
        pending_caption = None

        if para_is_mono(p):
            code_buf.append(text.replace("\t", "  "))
            continue
        if para_is_shaded(p) and code_buf:
            code_buf.append(text.replace("\t", "  "))
            continue
        flush_code()

        prefix, indent = list_prefix(p)
        if st == "ListParagraph" or prefix:
            prefix = prefix or "-"
            md.append(" " * indent + f"{prefix} " + inline(p))
            nxt = children[i + 1] if i + 1 < len(children) else None
            if nxt is None or nxt.tag != q("p") or (style_of(nxt) != "ListParagraph" and list_prefix(nxt)[0] is None):
                md.append("")
            continue

        if para_is_shaded(p):
            md.append("> " + inline(p).replace("\n", "\n> "))
            nxt = children[i + 1] if i + 1 < len(children) else None
            if nxt is None or nxt.tag != q("p") or not para_is_shaded(nxt) or para_is_mono(nxt):
                md.append("")
            else:
                md.append(">")
            continue

        md.append(inline(p))
        md.append("")
    flush_code()
    if not any(l.startswith("# ") for l in md):
        notes.append("the document has no Title style paragraph. A title was added from the file name.")
    return md, figs, notes


