def main(argv=None):
    ap = argparse.ArgumentParser(
        description="Render .docx, .md or .txt ground-truth documents as Markdown with stable anchors, a section index and figures.",
        epilog="Nothing is written with --dry-run. Word files are read with the standard library. "
               "Exit 2 means nothing was written: a finding needs the owner's decision, or the destination is not allowed.",
    )
    ap.add_argument("inputs", nargs="+", help="one or more .docx, .md or UTF-8 .txt files")
    ap.add_argument("--root", default=".", help="project root (default: current directory)")
    ap.add_argument("--out-dir", default=None,
                    help="output folder relative to --root (default: docs/ground-truth, or renderings/ in the private workspace "
                         "when the project's documents are not approved for repository readers or the source is restricted)")
    ap.add_argument("--name", help="output name without extension. Only valid with one input. Default: the input file name")
    ap.add_argument("--source-id", help="id of the source in plan.yaml, when the file name does not identify it. Only valid with one input")
    ap.add_argument("--source-label", help="original source path recorded in the header when the input is an agent-reviewed Markdown extraction. Only valid with one input")
    ap.add_argument("--version", default="unversioned", help="document version to record in the header (default: unversioned)")
    ap.add_argument("--date", default=dt.date.today().isoformat(), help="generation date, YYYY-MM-DD (default: today)")
    ap.add_argument("--show-review-items", action="store_true",
                    help="list the hidden text, tracked insertions and tracked deletions of a Word file for the owner, numbered, with the paragraph number and the text")
    ap.add_argument("--resolve-review-items", choices=("include", "exclude"),
                    help="the owner's decision on hidden text and tracked changes: include renders hidden text and insertions, "
                         "exclude leaves them out. Deleted text is never rendered. The decision is recorded in the header")
    ap.add_argument("--accept-marking-mismatch", action="store_true",
                    help="render a source whose header or footer marking (such as Internal) disagrees with its classification. The classification is not changed")
    ap.add_argument("--dry-run", action="store_true", help="render in memory and report, write nothing")
    a = ap.parse_args(argv)

    def fail(msg):
        print(f"error: {msg}. Nothing was written.", file=sys.stderr)
        return 2

    if a.name is not None and len(a.inputs) > 1:
        ap.error("--name works with a single input")
    if a.source_label is not None and len(a.inputs) > 1:
        ap.error("--source-label works with a single input")
    if a.source_id is not None and len(a.inputs) > 1:
        ap.error("--source-id works with a single input")
    if a.source_label is not None and not str(a.source_label).strip():
        ap.error("--source-label is empty")
    if a.name is not None and not (NAME_RE.fullmatch(a.name) and a.name.strip(".")):
        return fail(f"--name {a.name!r} must be a plain file name without a folder or an extension, such as architecture")
    if not valid_date(a.date):
        return fail(f"--date {a.date!r} is not a date. Write it as YYYY-MM-DD, such as 2027-02-01")
    if not str(a.version).strip():
        return fail("--version is empty. Give the document version, such as 0.3")
    why = L.root_problem(a.root)
    if why:
        return fail(why)
    root = Path(a.root).expanduser().resolve()
    if a.out_dir is not None and not str(a.out_dir).strip():
        return fail("--out-dir is empty. Leave it out for docs/ground-truth, or give a folder inside the project")
    name_max, path_max = L._limits()
    if a.out_dir is not None and any(len(part.encode("utf-8", "replace")) > name_max for part in Path(a.out_dir).parts):
        return fail(f"--out-dir holds a folder name longer than the {name_max} bytes the file system allows")

    # the private workspace, when the project has one, and the plan that says where renderings may go
    workspace, workspace_why = L.workspace_root(root)
    ctx = read_plan_context(root, workspace)
    if ctx["error"]:
        return fail(ctx["error"])
    explicit_out = inside_either(root, workspace, root / a.out_dir, "--out-dir") if a.out_dir is not None else None
    private_path = ctx["repo_audience_approved"] is False       # the owner answered no to the one question
    yes_path = ctx["repo_audience_approved"] is True
    if a.source_id is not None and not any(s["id"] == a.source_id for s in ctx["sources"]):
        return fail(f"--source-id {a.source_id} is not a source in the plan")

    def too_long(path):
        """Why path cannot be written on this file system, or None."""
        for part in path.parts:
            if len(part.encode("utf-8", "replace")) > name_max:
                return f"the name {part[:40]}... is longer than the {name_max} bytes the file system allows"
        if len(str(path).encode("utf-8", "replace")) >= path_max:
            return f"the path {str(path)[:40]}... is longer than the {path_max} bytes the file system allows"
        return None

    # 1. check every input and every output path
    jobs = []
    seen = {}
    for src in a.inputs:
        srcp = Path(src)
        if not L.exists(srcp):
            return fail(f"{src} does not exist" + (", or its name is longer than the file system allows" if too_long(srcp.absolute()) else ""))
        if srcp.is_dir():
            return fail(f"{src} is a folder, not a file. Name the document files to render")
        why = L.regular_file_problem(srcp)
        if why:
            return fail(why)
        ext = srcp.suffix.lower()
        if ext not in (".docx", ".md", ".markdown", ".txt"):
            return fail(f"{src}: direct rendering supports .docx, .md and UTF-8 .txt. Use the ground-truth skill's source-material procedure for PDF, image and other files")
        name = a.name or name_from_path(srcp)
        entry = match_source(ctx["sources"], srcp, name, root, workspace, a.source_id)
        sid = entry["id"] if entry else name
        declared = entry.get("classification") if entry else None
        if declared is not None and declared not in CLASSIFICATIONS:
            return fail(f"the classification of source {sid} must be public, repo-readers or restricted")
        classification = declared or ("repo-readers" if yes_path else "restricted" if private_path else None)
        aware = ctx["handling"] is not None or declared is not None   # the project uses the confidentiality fields
        out_dir, problem = choose_out_dir(root, workspace, workspace_why, explicit_out, private_path, classification, f"source {sid}")
        if problem:
            return fail(problem)
        if L.exists(out_dir) and not out_dir.is_dir():
            return fail(f"--out-dir {a.out_dir or 'docs/ground-truth'} is a file, not a folder")
        clash = overwrites_source(srcp, root, out_dir, a.name, workspace)
        if clash:
            print(f"error: {src} {clash}. "
                  "Keep the source in docs/source/ and render to docs/ground-truth/, the default. Nothing was written.", file=sys.stderr)
            return 2
        if name.casefold() in seen:
            return fail(f"{seen[name.casefold()]} and {src} would both render to {name}.md. Render them one at a time with --name, "
                        "or rename one of the files")
        seen[name.casefold()] = src
        fig_dir = L.inside(out_dir, out_dir / "figures" / name, "figures")
        out_md = L.inside(out_dir, out_dir / f"{name}.md", "--name")
        out_idx = L.inside(out_dir, out_dir / f"{name}.index.txt", "--name")
        for target in (out_md, out_idx, fig_dir):
            why = too_long(target)
            if why:
                return fail(f"{src} cannot be rendered to {name}: {why}. Pass a shorter --name or --out-dir")
        for target, what in ((out_md, "file"), (out_idx, "file"), (fig_dir, "folder")):
            if L.exists(target) and (not target.is_file() if what == "file" else not target.is_dir()):
                kind = "folder" if target.is_dir() else "file" if target.is_file() else "pipe, socket or device"
                return fail(f"{target} is in the way: it is a {kind} where the rendering writes a {what}")
        jobs.append({"src": src, "srcp": srcp, "ext": ext, "name": name, "entry": entry, "sid": sid,
                     "classification": classification, "aware": aware, "out_dir": out_dir,
                     "fig_dir": fig_dir, "out_md": out_md, "out_idx": out_idx})

    # 2. render every input in memory
    rendered = []
    gating = []
    for job in jobs:
        src, srcp, ext, name, sid = job["src"], job["srcp"], job["ext"], job["name"], job["sid"]
        try:
            if ext == ".docx":
                body, figs, notes, info = render_docx(srcp, f"figures/{name}", a.resolve_review_items)
            elif ext == ".txt":
                body, figs, notes, info = render_text(srcp)
            else:
                body, figs, notes, info = render_markdown(srcp, f"figures/{name}")
        except DocxError as e:
            return fail(f"{src}: {e}")
        except (ValueError, KeyError, IndexError, TypeError, AttributeError, RecursionError) as e:
            # a part of the document that is valid XML but not what Word writes
            return fail(f"{src}: a part of the document holds a value Word does not write ({type(e).__name__}: {str(e)[:120]}). Save the document again in Word")
        except OSError as e:
            return fail(f"cannot read {src}: {e.strerror or e}")
        for fname, _ in figs.files:
            target = job["fig_dir"] / fname
            why = too_long(target)
            if why:
                return fail(f"{src}: figure {fname[:40]} cannot be written: {why}")
            if L.exists(target) and not target.is_file():
                return fail(f"{target} is in the way: it is not a regular file where the rendering writes a figure")

        items, extras, findings = info["items"], [], []
        if info["markings"]:
            shown = " / ".join(info["markings"]).replace('"', "'")
            extras.append(f'markings: "{shown[:300]}"')
            if job["classification"] in ("repo-readers", "public") and marking_conflicts(info["markings"]):
                if a.accept_marking_mismatch:
                    extras.append("marking mismatch accepted by the owner")
                    findings.append(f"marking mismatch accepted for {sid}")
                else:
                    gating.append(f"marking disagrees with classification for {sid}")
        if items:
            job["review_lines"] = review_lines(sid, items) if a.show_review_items else []
            if a.resolve_review_items:
                extras.append(f"hidden or tracked content: {a.resolve_review_items} ({len(items)} items)")
                findings.append(f"hidden or tracked content in {sid}: {len(items)} items, owner decision {a.resolve_review_items}")
            elif job["aware"]:
                gating.append(f"hidden or tracked content found in {sid}: {len(items)} items; review with --show-review-items")
            else:
                findings.append(f"hidden or tracked content found in {sid}: {len(items)} items, rendered as Word shows them "
                                "(a legacy project is not stopped); review with --show-review-items")
        if info["links_removed"]:
            findings.append(f"link scheme removed in {sid} ({info['links_removed']} links)")
        if info["comments_removed"]:
            findings.append(f"HTML comments removed in {sid}: {info['comments_removed']}")
        text, index_txt, n_head = finish(body, a.source_label or srcp.name, a.version, a.date, extras)
        notes += unnumbered_notes(text)
        rendered.append((job, figs, notes, findings, text, index_txt, n_head))

    for job, figs, notes, findings, text, index_txt, n_head in rendered:
        for line in job.get("review_lines", []):
            print(line)
    if gating:
        for job, figs, notes, findings, text, index_txt, n_head in rendered:
            for f in findings:
                print(f"finding: {f}")
        for f in gating:
            print(f"finding: {f}")
        return fail(f"{len(gating)} finding(s) need the owner's decision. Show the owner what was found, then run this again with "
                    "--resolve-review-items include or exclude for hidden or tracked content and --accept-marking-mismatch for a marking")

    # 3. write, only when everything above worked
    def rel(p):
        if workspace is not None:
            ws = Path(workspace).resolve()
            if p == ws or ws in p.parents:
                return "workspace:" + p.relative_to(ws).as_posix()
        return str(p.relative_to(root)) if p.is_relative_to(root) else str(p)

    verb = "would write" if a.dry_run else "wrote"
    digests = {}
    for job, figs, notes, findings, text, index_txt, n_head in rendered:
        out_dir, out_md, out_idx, fig_dir, srcp = job["out_dir"], job["out_md"], job["out_idx"], job["fig_dir"], job["srcp"]
        if not a.dry_run:
            try:
                if figs.files:
                    fig_dir.mkdir(parents=True, exist_ok=True)
                for fname, data in figs.files:
                    (fig_dir / fname).write_bytes(data)
                out_md.parent.mkdir(parents=True, exist_ok=True)
                out_md.write_bytes(text.encode("utf-8"))
                out_idx.write_bytes(index_txt.encode("utf-8"))
            except OSError as e:
                print(f"error: cannot write the rendering of {srcp.name}: {e.strerror or e}. Check that you may write to {rel(out_dir)}", file=sys.stderr)
                return 2
        print(f"{verb} {rel(out_md)}: {len(text.splitlines())} lines, {n_head} headings, {len(figs)} figures")
        print(f"{verb} {rel(out_idx)}")
        for f in findings:
            print(f"finding: {f}")
        for n in notes:
            print(f"note: {srcp.name}: {n}")
        if job["entry"] is not None:
            values = {"rendering_sha256": L.sha256_text(text)}
            origin = srcp
            if a.source_label:
                label = Path(str(a.source_label))
                origin = next((c for c in ([label] if label.is_absolute() else [root / label] + ([Path(workspace) / label] if workspace is not None else []))
                               if L.exists(c) and c.is_file()), None)
                if origin is None:
                    print(f"note: {srcp.name}: content_sha256 of {job['sid']} was not recorded, because the original named by --source-label was not found")
            if origin is not None:
                try:
                    values["content_sha256"] = L.sha256_file(origin)
                except L.TextError as e:
                    return fail(str(e))
            digests[job["sid"]] = values
    print(f"{len(rendered)} document(s) {'checked' if a.dry_run else 'rendered'}")

    # 4. record the digests of what was read and what was written in the workspace plan
    if digests:
        ws_plan = Path(workspace) / "drafts" / "plan.yaml" if workspace is not None else None
        if ws_plan is not None and L.exists(ws_plan):
            target, where = ws_plan, "the workspace plan"
        elif yes_path and ctx["where"] == "project":
            target, where = ctx["path"], rel(Path(ctx["path"]).resolve())
        else:
            target, where = None, None
        if target is not None:
            if a.dry_run:
                print(f"would record content_sha256 and rendering_sha256 for {', '.join(sorted(digests))} in {where}")
            else:
                try:
                    done, missing, problem = record_source_digests(target, digests)
                except (L.TextError, ValueError, OSError) as e:
                    return fail(f"the digests could not be recorded in {where}: {e}")
                if problem:
                    return fail(f"the digests could not be recorded in {where}: {problem}")
                if done:
                    print(f"recorded content_sha256 and rendering_sha256 for {', '.join(done)} in {where}")
                for sid in missing:
                    print(f"note: source {sid} is not in {where}; its digests were not recorded")
    return 0


