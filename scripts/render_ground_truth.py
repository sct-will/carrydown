IMAGE_EXTENSIONS = {".png", ".jpg", ".jpeg", ".gif", ".svg", ".webp", ".bmp"}


class Figures:
    """The figures of one document, in memory until main writes them. Two figures with the same
    file name from different places get different names, so neither overwrites the other."""

    def __init__(self):
        self.files = []    # (name, bytes)
        self._by_key = {}
        self._names = set()

    def add(self, name, data, key=None):
        if key is not None and key in self._by_key:
            return self._by_key[key]
        stem, ext = os.path.splitext(name)
        final, n = name, 1
        while final.casefold() in self._names:
            n += 1
            final = f"{stem}-{n}{ext}"
        self._names.add(final.casefold())
        self.files.append((final, data))
        if key is not None:
            self._by_key[key] = final
        return final

    def __len__(self):
        return len(self.files)


def render_markdown(src, fig_prefix):
    try:
        text = Path(src).read_text(encoding="utf-8-sig")
    except UnicodeDecodeError as e:
        raise DocxError(f"is not UTF-8 text (byte 0x{e.object[e.start]:02x} at offset {e.start}). Save it as UTF-8, then run this again")
    text = text.replace("\r\n", "\n").replace("\r", "\n").replace("\t", "    ")
    text = re.sub(r"^<!-- Generated from .*?-->\s*\n", "", text, flags=re.S)
    lines = text.split("\n")
    notes = []
    figs = Figures()
    out = []
    fence = None
    for line in lines:
        m = re.match(r"^\s{0,3}(`{3,}|~{3,})", line)
        if m:
            tok = m.group(1)
            if fence is None:
                fence = tok[0]
            elif tok[0] == fence:
                fence = None
            out.append(line)
            continue
        if fence:
            out.append(line)
            continue

        def repl(mo):
            alt, target = mo.group(1), mo.group(2).strip()
            if re.match(r"^[a-z]+://", target) or target.startswith("#") or target.startswith("data:"):
                return mo.group(0)
            base = Path(src).parent.resolve()
            local = (base / target.split(" ")[0]).resolve()
            # copy only images that sit in the document's own folder or below it, so a link such as
            # ../../.env or /home/me/.ssh/id_ed25519 can never put a private file into the repository
            if base not in local.parents or local.suffix.lower() not in IMAGE_EXTENSIONS:
                notes.append(f"not copied (outside the document folder or not an image): {target}")
                return mo.group(0)
            try:
                found = local.is_file()
            except (OSError, ValueError):
                found = False
            if not found:
                notes.append(f"image not found, or not a regular file: {target}")
                return mo.group(0)
            try:
                data = local.read_bytes()
            except OSError as e:
                notes.append(f"image not readable ({e.strerror or e}): {target}")
                return mo.group(0)
            name = figs.add(local.name, data, key=str(local))
            return f"![{alt}]({fig_prefix}/{name})"

        line = re.sub(r"!\[([^\]]*)\]\(([^)]+)\)", repl, line)
        out.append(line)
    h1 = [h for h in collect_headings(out) if h[1] == 1]
    if not any(line.strip() for line in out):
        notes.append("the document is empty.")
    elif len(h1) == 0:
        notes.append("no top-level heading (#). A title was added from the file name.")
    elif len(h1) > 1:
        notes.append(f"{len(h1)} top-level headings. Use one # title and ## for sections so anchors stay readable.")
    return out, figs, notes


