def _set_key_in_text(text, source_id, key, value):
    """Set one key of one source in plan.yaml text, changing nothing else: comments, blank lines and
    the order of keys stay. Returns the new text, or None when the source is not written as a block
    (a flow mapping, for example) and the lines cannot be edited safely."""
    eol = "\r\n" if "\r\n" in text else "\n"
    ends_with_newline = text.endswith("\n")
    lines = text.replace("\r\n", "\n").split("\n")
    if ends_with_newline:
        lines.pop()
    start = next((i for i, ln in enumerate(lines) if re.match(r"^sources\s*:\s*(#.*)?$", ln)), None)
    if start is None:
        return None
    end = len(lines)
    for i in range(start + 1, len(lines)):
        ln = lines[i]
        if ln.strip() and not ln.lstrip().startswith("#") and not ln[0].isspace() and not ln.startswith("- "):
            end = i
            break
    starts, item_indent = [], None
    for i in range(start + 1, end):
        m = re.match(r"^(\s*)-(\s+)\S", lines[i])
        if m and (item_indent is None or len(m.group(1)) == item_indent):
            item_indent = len(m.group(1))
            starts.append((i, len(m.group(1)) + 1 + len(m.group(2))))

    def key_line(i, name, column):
        m = re.match(r"^(\s*)(-\s+)?" + re.escape(name) + r"\s*:(.*)$", lines[i])
        if m and len(m.group(1)) + (len(m.group(2)) if m.group(2) else 0) == column:
            return m
        return None

    for n, (first, column) in enumerate(starts):
        last = starts[n + 1][0] if n + 1 < len(starts) else end
        ident = None
        for i in range(first, last):
            m = key_line(i, "id", column)
            if m:
                raw = re.sub(r"\s+#.*$", "", m.group(3)).strip()
                ident = raw[1:-1] if len(raw) >= 2 and raw[0] == raw[-1] and raw[0] in "\"'" else raw
                break
        if ident != source_id:
            continue
        for i in range(first, last):
            if key_line(i, key, column):
                lines[i] = lines[i][:column] + f'{key}: "{value}"'
                break
        else:
            after = first
            for i in range(first, last):
                if lines[i].strip() and not lines[i].lstrip().startswith("#"):
                    after = i
            lines.insert(after + 1, " " * column + f'{key}: "{value}"')
        return eol.join(lines) + (eol if ends_with_newline else "")
    return None


def record_source_digests(plan_path, updates):
    """Write content_sha256 and rendering_sha256 into the sources[] entries of the plan at plan_path.
    updates maps a source id to {"content_sha256": ..., "rendering_sha256": ...}; a missing digest is
    left as it was. The lines of the plan are edited in place, so comments and layout stay. When a
    source is written in a form that cannot be edited that way, the plan is rewritten with the
    repository's dumper (the one plan_repair.py uses). The result is read back and compared with what
    was meant before it replaces the file. Returns (ids recorded, ids not found, problem or None)."""
    plan_path = Path(plan_path)
    why = L.regular_file_problem(plan_path)
    if why:
        raise L.TextError(why)
    data = plan_path.read_bytes()
    bom = data.startswith(b"\xef\xbb\xbf")
    try:
        original = data.decode("utf-8-sig")        # the line endings are kept as they are
    except UnicodeDecodeError:
        raise L.TextError(f"{plan_path.name} is not UTF-8 text. Save it as UTF-8, then run this again")
    raw = L.loads(original)
    sources = raw.get("sources") if isinstance(raw, dict) else None
    if not isinstance(sources, list):
        return [], sorted(updates), None
    present = {s.get("id") for s in sources if isinstance(s, dict)}
    wanted = {sid: {k: v for k, v in vals.items() if v} for sid, vals in updates.items() if sid in present}
    missing = sorted(sid for sid in updates if sid not in present)
    expected = L.loads(original)
    for s in expected["sources"]:
        if isinstance(s, dict) and s.get("id") in wanted:
            s.update(wanted[s["id"]])
    text = original
    for sid, vals in wanted.items():
        for key in DIGEST_KEYS:
            if key in vals and text is not None:
                text = _set_key_in_text(text, sid, key, vals[key])
    verified = False
    if text is not None:
        try:
            verified = L.loads(text) == expected
        except ValueError:
            verified = False
    if not verified:
        import plan_repair   # the dumper that already rewrites plans for the repair command
        text = plan_repair.dump(expected) + "\n"
        try:
            verified = L.loads(text) == expected
        except ValueError:
            verified = False
    if not verified:
        return [], missing, "the plan could not be rewritten without changing other values"
    if text != original:
        plan_path.write_bytes((b"\xef\xbb\xbf" if bom else b"") + text.encode("utf-8"))
    return sorted(wanted), missing, None


