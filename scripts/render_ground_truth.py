def inside_either(root, workspace, path, what="output"):
    """Return path, resolved, when it lies inside the project folder or the private workspace.
    Otherwise stop with the usual message that names the project folder."""
    base = Path(root).resolve()
    target = Path(path)
    target = (target if target.is_absolute() else base / target).resolve()
    if workspace is not None:
        ws = Path(workspace).resolve()
        if target == ws or ws in target.parents:
            return target
    return L.inside(root, path, what)


def read_plan_context(root, workspace):
    """The plan that governs where renderings go, read as plain data. The workspace plan
    (<workspace>/drafts/plan.yaml) comes first, because on the "no" path it is the only full plan;
    otherwise the project's plan. Returns a dict with plan, path, where, sources, repo_audience_approved
    and error. A plan that exists and cannot be read is an error, never a silent legacy project."""
    ctx = {"plan": None, "path": None, "where": None, "sources": [], "handling": None,
           "repo_audience_approved": None, "error": None}
    candidates = []
    if workspace is not None:
        candidates.append((Path(workspace) / "drafts" / "plan.yaml", "workspace"))
    candidates.append((L.find_plan(root), "project"))
    for path, where in candidates:
        if not L.exists(path):
            continue
        try:
            raw = L.load_file(path)
        except (L.TextError, ValueError, OSError, RecursionError):
            ctx["error"] = f"the {where} plan.yaml cannot be read, so the handling rules of the project are unknown. Fix the file, then run this again"
            return ctx
        if not isinstance(raw, dict):
            ctx["error"] = f"the {where} plan.yaml is not a mapping at the top level, so the handling rules of the project are unknown"
            return ctx
        ctx.update(plan=raw, path=Path(path), where=where)
        project = raw.get("project")
        handling = project.get("handling") if isinstance(project, dict) else None
        if handling is not None:
            if not isinstance(handling, dict):
                ctx["error"] = "project.handling in the plan must be a mapping"
                return ctx
            audience = handling.get("repo_audience_approved")
            if audience is not None and not isinstance(audience, bool):
                ctx["error"] = "project.handling.repo_audience_approved in the plan must be true or false"
                return ctx
            ctx.update(handling=handling, repo_audience_approved=audience)
        sources = raw.get("sources")
        if isinstance(sources, list):
            ctx["sources"] = [s for s in sources if isinstance(s, dict) and isinstance(s.get("id"), str)]
        return ctx
    return ctx


def match_source(sources, srcp, name, root, workspace, explicit_id=None):
    """The plan entry for an input file, or None. By id when --source-id is given; otherwise by the
    entry's source_path (under the project or the workspace), then by the name of its rendering, then
    by an id equal to the rendering name."""
    if explicit_id:
        return next((s for s in sources if s["id"] == explicit_id), None)
    real = os.path.normcase(os.path.realpath(str(srcp)))
    bases = [Path(root)] + ([Path(workspace)] if workspace is not None else [])
    for s in sources:
        sp = s.get("source_path")
        if isinstance(sp, str) and sp.strip() and "\x00" not in sp:
            for base in bases:
                if os.path.normcase(os.path.realpath(str(base / sp))) == real:
                    return s
    for s in sources:
        path = s.get("path")
        if isinstance(path, str) and path.strip() and name_from_path(path) == name:
            return s
    return next((s for s in sources if s["id"] == name), None)


def choose_out_dir(root, workspace, workspace_why, explicit_out, private_path, classification, label):
    """(out_dir, None) for the folder this source is rendered to, or (None, message).

    The path comes first: when the owner said not everyone who can read the repository may see the
    documents (private_path), every rendering goes to <workspace>/renderings, including the
    renderings of individually shareable sources. A restricted source needs the workspace on either path.
    Other sources keep the default, docs/ground-truth, as before."""
    restricted = classification == "restricted"
    if explicit_out is None:
        if not (private_path or restricted):
            return L.inside(root, Path(root) / "docs" / "ground-truth", "--out-dir"), None
        if workspace is None:
            why = workspace_why or "workspace-unavailable"
            return None, (f"{why}: {label} must be rendered in the private workspace, and none is usable. "
                          "Create it with workspace.py init, then run this again")
        return Path(workspace).resolve() / "renderings", None
    ws = Path(workspace).resolve() if workspace is not None else None
    if ws is not None and (explicit_out == ws or ws in explicit_out.parents):
        return explicit_out, None
    if private_path:
        return None, (f"drafting-is-private: the documents of this project are not approved for everyone who can read the repository, "
                      f"so {label} is rendered in the private workspace. Leave out --out-dir")
    if restricted:
        return None, (f"destination-not-allowed: {label} is classified restricted, so its rendering cannot be written "
                      "under the project folder. Leave out --out-dir to write it to the private workspace")
    return explicit_out, None


def marking_conflicts(markings):
    """True when a header or footer marking says the document is not for general readers."""
    joined = " ".join(markings).casefold()
    return any(word in joined for word in MARKING_WORDS)


def review_lines(source_id, items):
    """The numbered list for the owner's console. It shows the text, because the owner must see it
    to decide, so it is printed only by --show-review-items and written nowhere."""
    lines = [f"review items in {source_id}: {len(items)}"]
    for n, (para, kind, text) in enumerate(items, 1):
        shown = text if len(text) <= 400 else text[:400] + f" [{len(text) - 400} more characters]"
        lines.append(f"  {n}. paragraph {para}, {kind}: {shown}")
    return lines


