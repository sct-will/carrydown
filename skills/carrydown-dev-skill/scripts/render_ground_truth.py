#!/usr/bin/env python3
"""Render ground-truth documents as GitHub Flavored Markdown that a coding agent can cite.

The original document stays the source of truth. This script writes a derived
rendering for readers and agents:

  docs/ground-truth/<name>.md          the rendering, with a generated header and a section index
  docs/ground-truth/<name>.index.txt   one line per heading, "line:## heading", for sed-based reading
  docs/ground-truth/figures/<name>/    figures extracted from a .docx, or copied from a .md

Input can be a Word document (.docx) or a Markdown file (.md). Nothing needs to be
installed: Word files are read with the standard library (zipfile and xml.etree). If the
lxml package happens to be installed, the script uses it because it is faster.

Examples
  python3 scripts/render_ground_truth.py architecture.docx --version 0.2
  python3 scripts/render_ground_truth.py notes.md standards.md --out-dir docs/ground-truth
  python3 scripts/render_ground_truth.py architecture.docx --dry-run

With --dry-run nothing is written. The script reports what it would write.
"""
import argparse
import datetime as dt
import re
import shutil
import sys
import zipfile
from pathlib import Path

# ---------------------------------------------------------------------------
# Common helpers
# ---------------------------------------------------------------------------


def slugify(text):
    """GitHub heading anchor: lowercase, drop punctuation, spaces to hyphens."""
    s = text.strip().lower()
    s = re.sub(r"[^\w\s-]", "", s)
    s = re.sub(r"\s+", "-", s)
    return s


def esc_prose(t):
    return t.replace("<", "&lt;").replace(">", "&gt;")


def esc_cell(t):
    return t.replace("|", "\\|")


def name_from_path(p):
    return slugify(Path(p).stem.replace("_", "-")).strip("-") or "document"


def header_comment(src_name, version, date):
    return (
        f'<!-- Generated from "{src_name}" version {version} on {date}. '
        "The source file is the source of truth. Do not edit this file by hand. "
        "Regenerate it when the source changes with scripts/render_ground_truth.py. -->"
    )


def collect_headings(lines):
    """Return [(line_no, level, text)] for ATX headings outside code fences."""
    out = []
    fence = None
    for i, line in enumerate(lines, 1):
        m = re.match(r"^\s{0,3}(`{3,}|~{3,})", line)
        if m:
            tok = m.group(1)
            if fence is None:
                fence = tok[0]
            elif tok[0] == fence:
                fence = None
            continue
        if fence:
            continue
        h = re.match(r"^(#{1,6})\s+(.+?)\s*#*\s*$", line)
        if h:
            out.append((i, len(h.group(1)), h.group(2).strip()))
    return out


def anchors_for(headings):
    counts = {}
    result = []
    for _, _, text in headings:
        plain = re.sub(r"[`*_]", "", text)
        base = slugify(plain)
        n = counts.get(base, 0)
        counts[base] = n + 1
        result.append(base if n == 0 else f"{base}-{n}")
    return result


def build_index_block(lines_after_header, header_lines_count):
    """Section index as nested links, and the plain line index."""
    headings = collect_headings(lines_after_header)
    anchors = anchors_for(headings)
    md = []
    for (ln, lvl, text), anc in zip(headings, anchors):
        if lvl == 1:
            continue
        indent = "  " * (lvl - 2)
        label = esc_prose(re.sub(r"[`]", "", text))
        md.append(f"{indent}- [{label}](#{anc})")
    return md, headings


def finish(body_lines, src_name, version, date):
    """Assemble header, title, section index and body. Return (final_text, index_text, n_headings)."""
    # collapse runs of blank lines
    collapsed = []
    for line in body_lines:
        if line.strip() == "" and collapsed and collapsed[-1] == "":
            continue
        collapsed.append(line.rstrip() if line.strip() else "")
    while collapsed and collapsed[0] == "":
        collapsed.pop(0)
    collapsed = strip_old_index(collapsed)
    collapsed = [l for l in collapsed if not l.startswith("<!-- Generated from")]
    # split title (first H1) from the rest
    title_idx = next((i for i, l in enumerate(collapsed) if re.match(r"^#\s+\S", l)), None)
    if title_idx is None:
        title_line = "# " + Path(src_name).stem
        rest = collapsed
        pre = []
    else:
        title_line = collapsed[title_idx]
        pre = collapsed[:title_idx]
        rest = collapsed[title_idx + 1:]
    # subtitle lines directly after the title stay with the title
    sub = []
    def is_italic_line(l):
        return bool(re.match(r"^\*[^*].*\*$", l.strip()))

    while rest and (rest[0] == "" or is_italic_line(rest[0])) and len(sub) < 4:
        sub.append(rest.pop(0))
    while rest and rest[0] == "":
        rest.pop(0)
    provisional = [title_line] + sub + [""] + rest
    idx_md, _ = build_index_block(provisional, 0)
    out = [header_comment(src_name, version, date), ""] + pre + [title_line] + sub
    if sub and sub[-1] != "":
        out.append("")
    if idx_md:
        out += ["**Section index**", ""] + idx_md + [""]
    out += rest
    final = "\n".join(out).rstrip() + "\n"
    flines = final.split("\n")
    headings = collect_headings(flines)
    index_txt = "\n".join(f"{ln}:{'#' * lvl} {text}" for ln, lvl, text in headings) + "\n"
    return final, index_txt, len(headings)


def strip_old_index(lines):
    """Remove a previously generated section index so reruns are stable."""
    out = []
    i = 0
    while i < len(lines):
        if lines[i].strip() == "**Section index**":
            i += 1
            while i < len(lines) and (lines[i].strip() == "" or re.match(r"^\s*- \[", lines[i])):
                i += 1
            continue
        out.append(lines[i])
        i += 1
    return out


# ---------------------------------------------------------------------------
# Markdown input
# ---------------------------------------------------------------------------


def render_markdown(src, figures_dir, fig_prefix, write):
    text = Path(src).read_text(encoding="utf-8-sig")
    text = text.replace("\r\n", "\n").replace("\r", "\n").replace("\t", "    ")
    text = re.sub(r"^<!-- Generated from .*?-->\s*\n", "", text, flags=re.S)
    lines = text.split("\n")
    notes = []
    figs = 0
    out = []
    fence = None
    for line in lines:
        m = re.match(r"^\s{0,3}(`{3,}|~{3,})", line)
        if m:
            tok = m.group(1)
            if fence is None:
                fence = tok[0]
            elif tok[0] == fence:
                fence = None
            out.append(line)
            continue
        if fence:
            out.append(line)
            continue

        def repl(mo):
            nonlocal figs
            alt, target = mo.group(1), mo.group(2).strip()
            if re.match(r"^[a-z]+://", target) or target.startswith("#") or target.startswith("data:"):
                return mo.group(0)
            local = (Path(src).parent / target.split(" ")[0]).resolve()
            if not local.exists():
                notes.append(f"image not found: {target}")
                return mo.group(0)
            figs += 1
            if write:
                figures_dir.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(local, figures_dir / local.name)
            return f"![{alt}]({fig_prefix}/{local.name})"

        line = re.sub(r"!\[([^\]]*)\]\(([^)]+)\)", repl, line)
        out.append(line)
    h1 = [h for h in collect_headings(out) if h[1] == 1]
    if len(h1) == 0:
        notes.append("no top-level heading (#). A title was added from the file name.")
    elif len(h1) > 1:
        notes.append(f"{len(h1)} top-level headings. Use one # title and ## for sections so anchors stay readable.")
    return out, figs, notes


# ---------------------------------------------------------------------------
# Word input
# ---------------------------------------------------------------------------

W = "http://schemas.openxmlformats.org/wordprocessingml/2006/main"
R = "http://schemas.openxmlformats.org/officeDocument/2006/relationships"
A = "http://schemas.openxmlformats.org/drawingml/2006/main"
MONO_FONTS = ("Mono", "Consolas", "Courier", "Menlo", "Source Code")


def q(tag, ns=W):
    return "{%s}%s" % (ns, tag)


def render_docx(src, figures_dir, fig_prefix, write):
    try:
        from lxml import etree   # optional and faster
    except ImportError:
        import xml.etree.ElementTree as etree
    z = zipfile.ZipFile(src)
    doc = etree.fromstring(z.read("word/document.xml"))
    body = doc.find(q("body"))
    rels = {}
    if "word/_rels/document.xml.rels" in z.namelist():
        rels_xml = etree.fromstring(z.read("word/_rels/document.xml.rels"))
        rels = {r.get("Id"): r.get("Target") for r in rels_xml}

    num_fmt = {}
    if "word/numbering.xml" in z.namelist():
        num = etree.fromstring(z.read("word/numbering.xml"))
        abs_fmt = {}
        for a in num.findall(q("abstractNum")):
            lvl = a.find(q("lvl"))
            f = lvl.find(q("numFmt")) if lvl is not None else None
            abs_fmt[a.get(q("abstractNumId"))] = f.get(q("val")) if f is not None else "bullet"
        for n in num.findall(q("num")):
            num_fmt[n.get(q("numId"))] = abs_fmt.get(n.find(q("abstractNumId")).get(q("val")), "bullet")

    def style_of(p):
        ps = p.find(q("pPr") + "/" + q("pStyle"))
        return ps.get(q("val")) if ps is not None else "Normal"

    def heading_level(st):
        m = re.fullmatch(r"Heading\s*([1-6])", st or "", re.I)
        return int(m.group(1)) if m else None

    def is_heading_style(st):
        return st in ("Title",) or heading_level(st) is not None

    def ptext(p):
        parts = []
        for node in p.iter():
            if node.tag == q("t") and node.text:
                parts.append(node.text)
            elif node.tag == q("tab"):
                parts.append("\t")
            elif node.tag == q("br"):
                parts.append("\n")
        return "".join(parts)

    def rfont_mono(rf):
        return rf is not None and any(any(m in (rf.get(q(k)) or "") for m in MONO_FONTS) for k in ("ascii", "hAnsi", "cs"))

    def run_is_mono(r):
        rpr = r.find(q("rPr"))
        return rpr is not None and rfont_mono(rpr.find(q("rFonts")))

    def run_flag(r, tag):
        rpr = r.find(q("rPr"))
        if rpr is None:
            return False
        e = rpr.find(q(tag))
        return e is not None and e.get(q("val")) not in ("0", "false")

    def run_text(r):
        parts = []
        for node in r:
            if node.tag == q("t") and node.text:
                parts.append(node.text)
            elif node.tag == q("tab"):
                parts.append("  ")
            elif node.tag == q("br"):
                parts.append("\n")
        return "".join(parts)

    def para_is_mono(p):
        runs = [r for r in p.iter(q("r")) if run_text(r).strip()]
        if runs and all(run_is_mono(r) for r in runs):
            return True
        ppr = p.find(q("pPr"))
        if ppr is not None:
            mark = ppr.find(q("rPr"))
            if mark is not None and rfont_mono(mark.find(q("rFonts"))):
                return bool(runs) and all(r.find(q("rPr")) is None or r.find(q("rPr") + "/" + q("rFonts")) is None for r in runs)
        return False

    def para_is_shaded(p):
        shd = p.find(q("pPr") + "/" + q("shd"))
        return shd is not None and (shd.get(q("fill")) or "auto").lower() not in ("auto", "ffffff")

    def norm(t):
        return " ".join(t.split())

    # heading slugs in document order, the way GitHub derives anchors
    heading_texts = []
    for p in body.iter(q("p")):
        if is_heading_style(style_of(p)):
            t = norm(ptext(p))
            if t:
                heading_texts.append(t)
    counts = {}
    slug_list = []
    for t in heading_texts:
        b = slugify(re.sub(r"[`*_]", "", t))
        n = counts.get(b, 0)
        counts[b] = n + 1
        slug_list.append(b if n == 0 else f"{b}-{n}")
    text_to_slug = {}
    for t, sl in zip(heading_texts, slug_list):
        text_to_slug.setdefault(t, sl)

    bm_to_slug = {}
    pending = []
    for p in body.iter(q("p")):
        names = [b.get(q("name")) for b in p.iter(q("bookmarkStart"))]
        t = norm(ptext(p))
        if is_heading_style(style_of(p)) and t:
            sl = text_to_slug[t]
            for n in names + pending:
                bm_to_slug[n] = sl
            pending = []
        else:
            pending.extend(names)

    def inline(p, in_table=False):
        out = []

        def emit_runs(runs):
            buf = []
            state = {"kind": None, "text": ""}

            def flush():
                t, kind = state["text"], state["kind"]
                if not t:
                    return
                stripped = t.strip()
                lead = t[: len(t) - len(t.lstrip())]
                trail = t[len(t.rstrip()):]
                if kind == "m":
                    buf.append(lead + "`" + stripped + "`" + trail if stripped else t)
                elif kind in ("b", "i"):
                    mark = "**" if kind == "b" else "*"
                    buf.append(lead + mark + esc_prose(stripped) + mark + trail if stripped else t)
                else:
                    buf.append(esc_prose(t))
                state["text"] = ""

            for r in runs:
                t = run_text(r)
                if not t:
                    continue
                kind = "m" if run_is_mono(r) else "b" if run_flag(r, "b") else "i" if run_flag(r, "i") else "n"
                if kind != state["kind"]:
                    flush()
                    state["kind"] = kind
                state["text"] += t
            flush()
            return "".join(buf)

        for child in p:
            if child.tag == q("r"):
                out.append(emit_runs([child]))
            elif child.tag == q("hyperlink"):
                text = emit_runs(child.findall(q("r")))
                anchor = child.get(q("anchor"))
                rid = child.get(q("id", R))
                if anchor and anchor in bm_to_slug:
                    out.append(f"[{text}](#{bm_to_slug[anchor]})")
                elif rid and rid in rels:
                    out.append(f"[{text}]({rels[rid]})")
                else:
                    out.append(text)
            elif child.tag == q("ins"):
                out.append(emit_runs(child.findall(q("r"))))
        text = "".join(out)
        text = text.replace("****", "").replace("` `", " ")
        text = re.sub(r"`([^`]*)``([^`]*)`", r"`\1\2`", text)
        if in_table:
            text = esc_cell(text).replace("\n", "<br>")
        return text

    def list_prefix(p):
        numpr = p.find(q("pPr") + "/" + q("numPr"))
        if numpr is None:
            return None, 0
        nid = numpr.find(q("numId"))
        ilvl = numpr.find(q("ilvl"))
        fmt = num_fmt.get(nid.get(q("val")) if nid is not None else "", "bullet")
        level = int(ilvl.get(q("val"))) if ilvl is not None else 0
        return ("1." if fmt == "decimal" else "-"), level

    def code_lang(lines):
        first = next((l.strip() for l in lines if l.strip()), "")
        if first.startswith(("{", "[", '"')):
            return "json"
        if first.startswith(("import ", "const ", "export ", "await ", "(async", "function ")):
            return "js"
        if first.startswith("<"):
            return "html"
        if re.match(r"(?i)^(select|insert|update|create table|alter table)\b", first):
            return "sql"
        if first.startswith(("$ ", "npm ", "git ", "curl ", "python")):
            return "bash"
        return "text"

    def table_md(tbl):
        rows = []
        for tr in tbl.findall(q("tr")):
            cells = []
            for tc in tr.findall(q("tc")):
                paras = [inline(cp, in_table=True) for cp in tc.findall(q("p"))]
                paras = [x for x in paras if x.strip()]
                cells.append("<br>".join(paras) if paras else " ")
            rows.append(cells)
        if not rows:
            return []
        width = max(len(r) for r in rows)
        rows = [r + [" "] * (width - len(r)) for r in rows]
        lines = ["| " + " | ".join(rows[0]) + " |", "| " + " | ".join(["---"] * width) + " |"]
        for r in rows[1:]:
            lines.append("| " + " | ".join(r) + " |")
        return lines

    def drawing_target(p):
        for blip in p.iter(q("blip", A)):
            rid = blip.get(q("embed", R))
            if rid in rels:
                return rels[rid]
        return None

    md = []
    code_buf = []
    children = list(body)
    fig_counter = 0
    pending_caption = None
    notes = []

    def flush_code():
        nonlocal code_buf
        if code_buf:
            md.append("```" + code_lang(code_buf))
            md.extend(l.rstrip() for l in code_buf)
            md.append("```")
            md.append("")
            code_buf = []

    for i, el in enumerate(children):
        if el.tag == q("tbl"):
            flush_code()
            md.extend(table_md(el))
            md.append("")
            continue
        if el.tag != q("p"):
            continue
        p = el
        st = style_of(p)
        text = ptext(p)
        stripped = text.strip()

        target = drawing_target(p)
        if target:
            flush_code()
            fig_counter += 1
            caption = ""
            for nxt in children[i + 1:i + 3]:
                if nxt.tag == q("p"):
                    t = ptext(nxt).strip()
                    if t:
                        if re.match(r"^(Figure|Fig\.?) \d+[.:]", t):
                            caption = t
                        break
            m = re.match(r"^(?:Figure|Fig\.?) (\d+)[.:]", caption)
            ext = Path(target).suffix or ".png"
            name = f"figure-{m.group(1)}{ext}" if m else f"figure-{fig_counter}{ext}"
            member = "word/" + target if not target.startswith("/") else target.lstrip("/")
            if member not in z.namelist():
                member = "word/media/" + Path(target).name
            if write:
                figures_dir.mkdir(parents=True, exist_ok=True)
                (figures_dir / name).write_bytes(z.read(member))
            alt = re.sub(r"^(?:Figure|Fig\.?) \d+[.:]\s*", "", caption).rstrip(".") if caption else f"Figure {fig_counter}"
            md.append(f"![{esc_prose(alt)}]({fig_prefix}/{name})")
            md.append("")
            pending_caption = caption
            continue

        if not stripped:
            flush_code()
            continue

        # skip Word's own table of contents. The generated section index replaces it.
        if st.upper().startswith("TOC") or any((l.get(q("anchor")) or "").lower().startswith(("_toc", "toc_")) for l in p.findall(q("hyperlink"))):
            flush_code()
            continue

        if st == "Title":
            flush_code()
            md.append("# " + esc_prose(stripped))
            md.append("")
            continue
        if st == "Subtitle":
            md.append("*" + esc_prose(stripped) + "*")
            md.append("")
            continue
        lvl = heading_level(st)
        if lvl:
            flush_code()
            md.append("#" * (lvl + 1 if lvl < 6 else 6) + " " + esc_prose(stripped))
            md.append("")
            continue

        if pending_caption and stripped == pending_caption:
            md.append("*" + esc_prose(stripped) + "*")
            md.append("")
            pending_caption = None
            continue
        pending_caption = None

        if para_is_mono(p):
            code_buf.append(text.replace("\t", "  "))
            continue
        if para_is_shaded(p) and code_buf:
            code_buf.append(text.replace("\t", "  "))
            continue
        flush_code()

        prefix, level = list_prefix(p)
        if st == "ListParagraph" or prefix:
            prefix = prefix or "-"
            md.append("  " * level + f"{prefix} " + inline(p))
            nxt = children[i + 1] if i + 1 < len(children) else None
            if nxt is None or nxt.tag != q("p") or (style_of(nxt) != "ListParagraph" and list_prefix(nxt)[0] is None):
                md.append("")
            continue

        if para_is_shaded(p):
            md.append("> " + inline(p).replace("\n", "\n> "))
            nxt = children[i + 1] if i + 1 < len(children) else None
            if nxt is None or nxt.tag != q("p") or not para_is_shaded(nxt) or para_is_mono(nxt):
                md.append("")
            else:
                md.append(">")
            continue

        md.append(inline(p))
        md.append("")
    flush_code()
    if not any(l.startswith("# ") for l in md):
        notes.append("the document has no Title style paragraph. A title was added from the file name.")
    return md, fig_counter, notes


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------


def main(argv=None):
    ap = argparse.ArgumentParser(
        description="Render .docx or .md ground-truth documents as Markdown with stable anchors, a section index and figures.",
        epilog="Nothing is written with --dry-run. Word files are read with the standard library.",
    )
    ap.add_argument("inputs", nargs="+", help="one or more .docx or .md files")
    ap.add_argument("--root", default=".", help="project root (default: current directory)")
    ap.add_argument("--out-dir", default="docs/ground-truth", help="output folder relative to --root (default: docs/ground-truth)")
    ap.add_argument("--name", help="output name without extension. Only valid with one input. Default: the input file name")
    ap.add_argument("--version", default="unversioned", help="document version to record in the header (default: unversioned)")
    ap.add_argument("--date", default=dt.date.today().isoformat(), help="generation date (default: today)")
    ap.add_argument("--dry-run", action="store_true", help="render in memory and report, write nothing")
    a = ap.parse_args(argv)
    if a.name and len(a.inputs) > 1:
        ap.error("--name works with a single input")
    root = Path(a.root)
    out_dir = root / a.out_dir
    total = 0
    for src in a.inputs:
        srcp = Path(src)
        if not srcp.exists():
            print(f"error: {src} does not exist", file=sys.stderr)
            return 2
        ext = srcp.suffix.lower()
        if ext not in (".docx", ".md", ".markdown"):
            print(f"error: {src}: only .docx and .md are supported", file=sys.stderr)
            return 2
        name = a.name or name_from_path(srcp)
        fig_dir = out_dir / "figures" / name
        fig_prefix = f"figures/{name}"
        write = not a.dry_run
        if ext == ".docx":
            body, figs, notes = render_docx(srcp, fig_dir, fig_prefix, write)
        else:
            body, figs, notes = render_markdown(srcp, fig_dir, fig_prefix, write)
        text, index_txt, n_head = finish(body, srcp.name, a.version, a.date)
        out_md = out_dir / f"{name}.md"
        out_idx = out_dir / f"{name}.index.txt"
        verb = "would write" if a.dry_run else "wrote"
        if write:
            out_dir.mkdir(parents=True, exist_ok=True)
            out_md.write_text(text, encoding="utf-8")
            out_idx.write_text(index_txt, encoding="utf-8")
        rel = lambda p: str(p.relative_to(root)) if p.is_relative_to(root) else str(p)
        print(f"{verb} {rel(out_md)}: {len(text.splitlines())} lines, {n_head} headings, {figs} figures")
        print(f"{verb} {rel(out_idx)}")
        for n in notes:
            print(f"note: {srcp.name}: {n}")
        total += 1
    print(f"{total} document(s) {'checked' if a.dry_run else 'rendered'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
